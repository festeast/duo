export function WordPic({ w, size = 40 }: { w: Word; size?: number }) {
  const num = NUMBER[w.tr]
  if (num)
    return (
      <span className="pic" style={{ width: size, height: size, borderRadius: size / 3, color: 'var(--blue)', background: 'color-mix(in srgb, var(--blue) 13%, transparent)', fontWeight: 900, fontSize: size * (num.length > 2 ? 0.28 : 0.42) }} aria-hidden>
        {num}
      </span>
    )
  const dot = COLOR_WORD[w.tr]
  if (dot)
    return (
      <span className="pic" style={{ width: size, height: size, borderRadius: size / 3, background: 'var(--card-2)' }} aria-hidden>
        <span style={{ width: size * 0.46, height: size * 0.46, borderRadius: '50%', background: dot, boxShadow: 'inset 0 0 0 1.5px rgba(0,0,0,.12)' }} />
      </span>
    )
  return <Pic I={wordIcon(w)} size={size} color={LEVEL_COLOR[w.level] ?? LEVEL_COLOR[1]} round={size / 3} />
}

